/**
 * Vendors the Corelith brand typeface into the film.
 *
 *   node scripts/fetch-brand-fonts.mjs
 *
 * Chakra Petch is not a choice made here. It is the face the company's own site sets everything in
 * — `corelith-web/src/app/layout.tsx` loads it as `--font-chakra` and `globals.css` maps both
 * `--font-display` and `--font-sans` to it — and its squared terminals and slight condensation are
 * what give the wordmark and the headlines the same voice. The film previously set its copy in
 * Geist, which is PARALITH's *interface* font and the wrong instrument for a brand statement.
 *
 * JetBrains Mono comes along for the same reason: it is `--font-mono` on the site, the face the
 * brand stamps versions and checksums in. It is used for the film's own chrome only. Terminals
 * inside the product twin stay Cascadia Mono, because that is what `AppSettings::default()` gives
 * a PARALITH terminal on a real install.
 *
 * Both are SIL Open Font License 1.1. The faces are downloaded once, written into
 * `public/fonts/`, and inlined as data URIs by `src/brand-fonts.ts` — the film never fetches a
 * font at render time, for the delayRender reason documented in `src/fonts.ts`.
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const FONTS = path.join(ROOT, 'public', 'fonts');
const SRC = path.join(ROOT, 'src');

/** A desktop Chrome UA is what makes the Google Fonts API answer with woff2 rather than ttf. */
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

const FAMILIES = [
  {
    name: 'Chakra Petch',
    query: 'Chakra+Petch:wght@300;400;500;600;700',
    file: 'chakra-petch',
    constant: 'CHAKRA_PETCH',
  },
  {
    name: 'JetBrains Mono',
    query: 'JetBrains+Mono:wght@400;500;600',
    file: 'jetbrains-mono',
    constant: 'JETBRAINS_MONO',
  },
];

const fetchText = async (url) => {
  const response = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!response.ok) throw new Error(`${response.status} for ${url}`);
  return response.text();
};

const fetchBuffer = async (url) => {
  const response = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!response.ok) throw new Error(`${response.status} for ${url}`);
  return Buffer.from(await response.arrayBuffer());
};

mkdirSync(FONTS, { recursive: true });

const modules = [];

for (const family of FAMILIES) {
  const css = await fetchText(
    `https://fonts.googleapis.com/css2?family=${family.query}&display=block`,
  );

  /**
   * Google serves one `@font-face` per weight per unicode subset. The film sets Latin copy only,
   * so the Thai, Vietnamese and Latin-Extended cuts are dropped — keeping them would roughly
   * quadruple an already large inlined payload for glyphs no frame contains.
   */
  const blocks = css.split('@font-face').slice(1);
  const faces = [];

  for (const block of blocks) {
    const subset = /\/\*\s*([a-z-]+)\s*\*\//.exec(block)?.[1] ?? '';
    const isLatin = block.includes('U+0000-00FF') || subset === 'latin';
    if (!isLatin) continue;

    const url = /src:\s*url\((https:[^)]+\.woff2)\)/.exec(block)?.[1];
    const weight = /font-weight:\s*(\d+)/.exec(block)?.[1];
    if (!url || !weight) continue;
    if (faces.some((face) => face.weight === weight)) continue;

    const buffer = await fetchBuffer(url);
    const filename = `${family.file}-${weight}.woff2`;
    writeFileSync(path.join(FONTS, filename), buffer);
    faces.push({ weight, filename, base64: buffer.toString('base64'), bytes: buffer.length });
    console.log(`${family.name} ${weight}  ${(buffer.length / 1024).toFixed(1)} kB  -> public/fonts/${filename}`);
  }

  if (faces.length === 0) throw new Error(`No Latin faces resolved for ${family.name}`);

  modules.push(
    [
      `/** ${family.name}, Latin subset, one entry per weight. Generated by scripts/fetch-brand-fonts.mjs. */`,
      `export const ${family.constant}: readonly { weight: number; src: string }[] = [`,
      ...faces.map(
        (face) =>
          `  { weight: ${face.weight}, src: 'data:font/woff2;base64,${face.base64}' },`,
      ),
      '];',
    ].join('\n'),
  );
}

writeFileSync(
  path.join(SRC, 'brand-font-data.ts'),
  `${[
    '// Generated by scripts/fetch-brand-fonts.mjs. Do not edit by hand.',
    '//',
    '// Chakra Petch and JetBrains Mono, both SIL Open Font License 1.1, inlined as data URIs so the',
    '// film never awaits a network fetch mid-render. See scripts/fetch-brand-fonts.mjs for why these',
    '// are the brand faces rather than a choice made in this project.',
    '',
    ...modules,
  ].join('\n')}\n`,
  'utf8',
);

console.log('\nwrote src/brand-font-data.ts');
